def test_privacy_scan_flags_and_excludes(tmp_path):
    files = dict(CLEAN_FILES)
    files["Doc/tutorial/introduction.rst"] = (
        "Contact alice@example.com or call (555) 123-4567.\n"
    )
    manifest_path, raw_dir, _ = _make_manifest_and_raw(
        tmp_path, files, privacy_status="private-content-excluded"
    )
    manifest = load_source_manifest(manifest_path)
    corpus = build_real_local_corpus(manifest, raw_dir)

    assert not corpus.privacy.clean
    excluded = corpus.excluded_document_ids
    assert "doc-tutorial-introduction.rst" in excluded
    assert all(doc.doc_id != "doc-tutorial-introduction.rst" for doc in corpus.documents)
    derived_text = "\n".join(chunk.text for chunk in corpus.chunks())
    assert "alice@example.com" not in derived_text
    assert "(555) 123-4567" not in derived_text
    categories = {finding.category for finding in corpus.privacy.findings}
    assert {"email", "phone"} <= categories
    assert all(finding.source_path == "Doc/tutorial/introduction.rst" for finding in corpus.privacy.findings)


