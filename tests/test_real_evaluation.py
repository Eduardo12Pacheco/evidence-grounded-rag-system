def _write_manifest(tmp_path: Path, data: dict[str, object]) -> Path:
    path = tmp_path / "manifest.json"
    path.write_text(json.dumps(data), encoding="utf-8")
    return path


def _make_manifest_and_raw(
    tmp_path: Path, files: dict[str, str], **overrides
) -> tuple[Path, Path]:
    raw_dir = tmp_path / "tmpraw"
    entries: list[dict[str, object]] = []
    for rel, text in files.items():
        path = raw_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        raw = path.read_bytes()
        entries.append({"path": rel, "size": len(raw), "sha256": sha256_bytes(raw)})
    data = _manifest_data(
        expected_files=entries, document_count=len(entries), **overrides
    )
    return _write_manifest(tmp_path, data), raw_dir


def _json_bytes(data: dict[str, object]) -> bytes:
    return (json.dumps(data, indent=2, sort_keys=True) + "\n").encode("utf-8")


def _deterministic_digest(data: dict[str, object]) -> str:
    import hashlib

    payload = {
        k: v
        for k, v in data.items()
        if k not in ("timestamp_utc", "deterministic_digest")
    }
    return hashlib.sha256(_json_bytes(payload)).hexdigest()


