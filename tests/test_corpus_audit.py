def test_raw_vs_normalized_checksum_distinction():
    raw = b"Raw bytes with trailing spaces.  \n\nAnd a trailing newline.\n"
    text = raw.decode("utf-8")
    raw_digest = sha256_bytes(raw)
    normalized_digest = sha256_hex(text)
    assert raw_digest != normalized_digest
    assert len(raw_digest) == 64
    assert len(normalized_digest) == 64
    assert sha256_bytes(raw) == raw_digest
    assert sha256_hex(text) == normalized_digest


def test_normalized_checksum_hashes_exact_normalized_document_text(tmp_path):
    # Normalization changes these bytes: NFKC (Roman-numeral ⅰⅱⅲ -> i ii iii),
    # form-feed control char (removed), non-breaking spaces, whitespace runs,
    # and trailing whitespace (stripped). The derived normalized checksum must
    # hash that exact normalized string, not the raw captured text.
    raw_text = "Price: \u2170 \u2171 \u2172\f\n\n  Total\u00a0\u00a0due  \n"
    manifest_path, raw_dir, _ = _make_manifest_and_raw(
        tmp_path, {"Doc/reference/lexical_analysis.rst": raw_text}
    )
    manifest = load_source_manifest(manifest_path)
    corpus = build_real_local_corpus(manifest, raw_dir)
    document = corpus.documents[0]

    normalized = normalize_text(raw_text)
    assert raw_text != normalized
    assert normalized == "Price: i ii iii Total due"

    assert document.raw_sha256 != document.normalized_sha256
    assert document.normalized_sha256 == sha256_hex(normalized)
    assert document.normalized_sha256 == sha256_hex(normalize_text(raw_text))

    # Chunk checksums and IDs stay deterministic and are derived from the same
    # normalized document text used for chunking.
    rebuilt = build_real_local_corpus(manifest, raw_dir)
    assert corpus.chunks() == rebuilt.chunks()
    assert document.chunks
    for chunk in document.chunks:
        assert chunk.text in normalized
        assert chunk.checksum_sha256 == sha256_hex(chunk.text)
        assert chunk.chunk_id == derive_chunk_id(document.doc_id, chunk.seq)


