def test_report_deterministic_portion_is_timestamp_independent(tmp_path, raw_copy):
    _, first_path = real_evaluate(
        MANIFEST, QUERY_SET, raw_copy, out_path=tmp_path / "r1.json"
    )
    _, second_path = real_evaluate(
        MANIFEST, QUERY_SET, raw_copy, out_path=tmp_path / "r2.json"
    )
    first = json.loads(first_path.read_text(encoding="utf-8"))
    second = json.loads(second_path.read_text(encoding="utf-8"))
    first_payload = {
        k: v
        for k, v in first.items()
        if k not in ("timestamp_utc", "deterministic_digest")
    }
    second_payload = {
        k: v
        for k, v in second.items()
        if k not in ("timestamp_utc", "deterministic_digest")
    }
    assert _json_bytes(first_payload) == _json_bytes(second_payload)
    assert {
        k: v
        for k, v in first.items()
        if k not in ("timestamp_utc", "deterministic_digest")
    } == {
        k: v
        for k, v in second.items()
        if k not in ("timestamp_utc", "deterministic_digest")
    }
    assert first["deterministic_digest"] == second["deterministic_digest"]
    assert first["deterministic_digest"] == _deterministic_digest(first)


def test_citations_resolve_with_version_and_excerpt_checksums(
    tmp_path, raw_copy, real_corpus
):
    report, _ = real_evaluate(
        MANIFEST, QUERY_SET, raw_copy, out_path=tmp_path / "report.json"
    )
    checked = 0
    for queries in report.data["per_query"].values():
        for record in queries.values():
            exposed = set(record["retrieved_chunk_ids"])
            for citation in record["citations"]:
                checked += 1
                chunk = real_corpus.chunk_by_id(citation["chunk_id"])
                assert chunk is not None
                assert citation["chunk_id"] in exposed
                assert citation["corpus_version"] == chunk.corpus_version
                assert citation["location"] == chunk.location
                assert citation["excerpt_sha256"] == chunk.checksum_sha256
                assert citation["excerpt_prefix"] == chunk.text[:120]
                assert citation["excerpt_matches"] is True
                assert len(citation["excerpt_prefix"]) <= 120
    assert checked > 0


